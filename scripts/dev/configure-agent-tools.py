"""Configure project-scoped MCP clients without changing global user settings."""
import datetime
import json
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parents[2]
manifest_path = ROOT / '.agents/tooling.json'
current = None
if manifest_path.exists():
    current = json.loads(manifest_path.read_text(encoding='utf-8'))
    versions = current['stdioServers']
    revisions = {repo: definition['revision'] for repo, definition in current['repositories'].items()}
else:
    versions = json.loads((ROOT / '.tmp/agent-tool-versions.json').read_text(encoding='utf-8'))
    revisions = json.loads((ROOT / '.tmp/agent-source-revisions.json').read_text(encoding='utf-8'))
manifest = {
    'schemaVersion': 1,
    'repositories': {repo: {'url': f'https://github.com/{repo}', 'revision': revision} for repo, revision in revisions.items()},
    'skills': {
        'playwright':'openai/skills', 'security-best-practices':'openai/skills', 'security-threat-model':'openai/skills',
        'gh-fix-ci':'openai/skills', 'gh-address-comments':'openai/skills', 'sentry':'openai/skills',
        'react-best-practices':'vercel-labs/agent-skills', 'web-design-guidelines':'vercel-labs/agent-skills', 'use-railway':'railwayapp/railway-skills',
    },
    'stdioServers': {
        'context7': {**versions['context7'], 'args':[]},
        'playwright': {**versions['playwright'], 'args':['--headless', '--browser', 'chrome']},
        'chrome-devtools': {**versions['chrome-devtools'], 'args':['--headless', '--isolated', '--no-usage-statistics', '--no-performance-crux']},
        'railway': {**versions['railway'], 'args':['mcp']},
    },
    'httpServers': {
        'openaiDeveloperDocs': {'url':'https://developers.openai.com/mcp'},
        'github': {'url':'https://api.githubcopilot.com/mcp/', 'tokenEnv':'GITHUB_PERSONAL_ACCESS_TOKEN'},
        'sentry': {'url':'https://mcp.sentry.dev/mcp', 'authentication':'OAuth'},
    },
}
if current is not None:
    manifest = current
(ROOT / '.agents/tooling.json').write_text(json.dumps(manifest, indent=2, ensure_ascii=False)+'\n', encoding='utf-8')
launcher = (ROOT / 'scripts/dev/mcp-server.mjs').as_posix()
managed = {name:{'command':'node', 'args':[launcher,name]} for name in manifest['stdioServers']}
for name, server in manifest['httpServers'].items():
    managed[name] = {'type':'http', 'url':server['url']}
    if server.get('tokenEnv'):
        managed[name]['headers'] = {'Authorization':'Bearer ${'+server['tokenEnv']+'}'}

timestamp = datetime.datetime.now(datetime.timezone.utc).strftime('%Y%m%dT%H%M%SZ')
for relative, cursor in [('.mcp.json',False),('.cursor/mcp.json',True)]:
    target = ROOT / relative
    content = json.loads(target.read_text(encoding='utf-8-sig')) if target.exists() else {}
    if target.exists():
        backup = ROOT / '.tmp/agent-setup-backups' / timestamp / relative.lstrip('.')
        backup.parent.mkdir(parents=True,exist_ok=True)
        shutil.copy2(target,backup)
    additions = json.loads(json.dumps(managed))
    if cursor:
        for entry in additions.values():
            for key, value in entry.get('headers',{}).items():
                entry['headers'][key] = value.replace('${GITHUB_PERSONAL_ACCESS_TOKEN}','${env:GITHUB_PERSONAL_ACCESS_TOKEN}')
    content.setdefault('mcpServers',{}).update(additions)
    target.parent.mkdir(parents=True,exist_ok=True)
    target.write_text(json.dumps(content,indent=2,ensure_ascii=False)+'\n',encoding='utf-8')

target = ROOT / '.codex/config.toml'
if target.exists() and '# Generated by scripts/dev/configure-agent-tools.py' not in target.read_text(encoding='utf-8'):
    raise SystemExit('Existing project Codex config is unmanaged; merge it explicitly instead of overwriting.')
lines = ['# Generated by scripts/dev/configure-agent-tools.py; global user configuration is unchanged.',
         'approval_policy = "on-request"', 'sandbox_mode = "workspace-write"', '',
         '[agents]', 'enabled = true', 'max_concurrent_threads_per_session = 4', '']
for name, server in manifest['stdioServers'].items():
    lines += [f'[mcp_servers.{json.dumps(name)}]', 'command = "node"', f'args = {json.dumps([launcher,name])}', 'startup_timeout_sec = 60', 'tool_timeout_sec = 120', '']
for name, server in manifest['httpServers'].items():
    lines += [f'[mcp_servers.{json.dumps(name)}]', f'url = {json.dumps(server["url"])}', 'startup_timeout_sec = 30']
    if server.get('tokenEnv'):
        lines += [f'bearer_token_env_var = {json.dumps(server["tokenEnv"])}']
    lines += ['']
target.write_text('\n'.join(lines),encoding='utf-8')
rules = ROOT / '.codex/rules/rappel-beauty.rules'
rules.parent.mkdir(parents=True,exist_ok=True)
allow = [['npm.cmd','run'],['npm','run'],['npx','tsc'],['npx','vitest'],['npx','playwright'],['npx','prisma','generate'],['npx','prisma','migrate','status'],
         ['git','status'],['git','diff'],['git','log'],['git','show'],['git','branch'],['gh','pr','view'],['gh','pr','list'],['gh','pr','checks'],['gh','run','list'],['gh','run','view']]
forbid = [['git','push','--force'],['git','push','-f'],['git','reset','--hard'],['git','clean'],['npx','prisma','migrate','deploy'],['railway','up'],['railway','redeploy']]
rl = ['# Generated by scripts/dev/configure-agent-tools.py. Mirrors .claude/settings.json.']
rl += [f'prefix_rule(pattern={json.dumps(x)}, decision="allow")' for x in allow]
rl += [f'prefix_rule(pattern={json.dumps(x)}, decision="forbidden")' for x in forbid]
rules.write_text(chr(10).join(rl)+chr(10),encoding='utf-8')

cli = ROOT / '.cursor/cli.json'
cli_content = {'permissions': {
    'allow': ['Read(**)','Write(src/**)','Write(tests/**)','Write(docs/**)','Write(scripts/**)','Write(.agents/**)','Write(.claude/**)','Write(.cursor/**)','Write(.codex/**)','Write(AGENTS.md)','Write(CLAUDE.md)',
              'Shell(npm.cmd)','Shell(npm)','Shell(npx)','Shell(node)','Shell(python)','Shell(git status)','Shell(git diff)','Shell(git log)','Shell(git show)','Shell(gh pr)','Shell(gh run)'],
    'deny': ['Read(.env*)','Write(.env*)','Shell(git push --force)','Shell(git reset --hard)','Shell(git clean)','Shell(railway up)','Shell(railway redeploy)','Shell(rm -rf)']}}
cli.write_text(json.dumps(cli_content,indent=2)+chr(10),encoding='utf-8')

print(json.dumps({'managed_mcp_servers':len(managed),'clients':['Codex','Cursor','Claude Code'],'global_settings_changed':False}))
